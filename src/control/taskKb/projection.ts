import type { Db } from "../db.js";
import type { SandboxContainer } from "../sandbox/container.js";

/**
 * The knowledge base as plain files in the sandbox (`kb/INDEX.md`, `kb/wiki/<domain>/<id>.md`),
 * for whatever reads files rather than calling tools: terminals, notebooks, sub-agents.
 * They are a copy rendered from the database, rewritten after every change; editing
 * them changes nothing.
 */

const HEADER = "<!-- Generated by Clawpage Agent's knowledge maintainer from the personal knowledge base. Edits here are overwritten; to change something, use aio_task_kb kb_propose. -->";
const INDEX_CHARS = 60_000;

export function renderKbIndex(db: Db, ownerId: string): string {
  const nodes = db.prepare("SELECT id, kind, domain, title, summary, wiki_md IS NOT NULL AS wiki FROM kb_nodes WHERE owner_id=? AND status='active' ORDER BY domain, reads DESC, updated_at DESC").all(ownerId) as Array<{ id: string; kind: string; domain: string; title: string; summary: string; wiki: number }>;
  const edges = db.prepare("SELECT e.src, e.rel, n.title FROM kb_edges e JOIN kb_nodes n ON n.id=e.dst JOIN kb_nodes s ON s.id=e.src WHERE s.owner_id=? AND n.status='active'").all(ownerId) as Array<{ src: string; rel: string; title: string }>;
  const out = new Map<string, string[]>();
  for (const e of edges) { const list = out.get(e.src) ?? []; list.push(`${e.rel} ${e.title}`); out.set(e.src, list); }
  const lines = [HEADER, "", "# Personal knowledge base: index", "", `${nodes.length} nodes. Read a node with aio_task_kb kb_get <id>; pages under wiki/ are checked quick references.`];
  let domain = "";
  for (const n of nodes) {
    if (n.domain !== domain) { domain = n.domain; lines.push("", `## ${domain}`, ""); }
    const links = (out.get(n.id) ?? []).slice(0, 4);
    lines.push(`- **${n.title}** (${n.kind}, \`${n.id}\`${n.wiki ? `, wiki/${n.domain}/${n.id}.md` : ""})${n.summary ? `: ${n.summary}` : ""}${links.length ? ` → ${links.join("; ")}` : ""}`);
    if (lines.join("\n").length > INDEX_CHARS) { lines.push("", "… (more nodes: search with kb_search)"); break; }
  }
  return lines.join("\n") + "\n";
}

export async function renderKbProjection(opts: { db: Db; ownerId: string; workspaceDir: string; container: Pick<SandboxContainer, "execInSandbox" | "writeFileInSandbox"> }): Promise<void> {
  const { db, ownerId, workspaceDir, container } = opts;
  const root = `${workspaceDir}/kb`;
  const pages = db.prepare("SELECT id, domain, title, wiki_md, wiki_at FROM kb_nodes WHERE owner_id=? AND status='active' AND wiki_md IS NOT NULL").all(ownerId) as Array<{ id: string; domain: string; title: string; wiki_md: string; wiki_at: number }>;
  const dirs = [...new Set(pages.map((p) => `${root}/wiki.next/${p.domain}`))];
  const prep = await container.execInSandbox(["bash", "-c", 'rm -rf -- "$1/wiki.next" && mkdir -p -- "$1/wiki.next" "${@:2}"', "kb-prep", root, ...dirs], { timeoutMs: 30_000 });
  if (prep.code !== 0) throw new Error(prep.stderr.trim().slice(0, 200) || `exit ${prep.code}`);
  for (const p of pages) {
    await container.writeFileInSandbox(`${root}/wiki.next/${p.domain}/${p.id}.md`, `${HEADER}\n\n# ${p.title}\n\n${p.wiki_md}\n\n_Checked ${new Date(p.wiki_at).toISOString().slice(0, 10)} · node \`${p.id}\`_\n`);
  }
  await container.writeFileInSandbox(`${root}/INDEX.md`, renderKbIndex(db, ownerId));
  const swap = await container.execInSandbox(["bash", "-c", 'rm -rf -- "$1/wiki" && mv -- "$1/wiki.next" "$1/wiki"', "kb-swap", root], { timeoutMs: 30_000 });
  if (swap.code !== 0) throw new Error(swap.stderr.trim().slice(0, 200) || `exit ${swap.code}`);
}
